export type LottieName = keyof typeof LOTTIE_ASSETS;

class LottieManager {
      get(name: LottieName) {
            return LOTTIE_ASSETS[name];
      }

      getDefaultSize(name: LottieName): { width: number; height: number } {
            switch (name) {
                  case 'loading':
                        return { width: 64, height: 64 };
                  case 'error':
                        return { width: 160, height: 160 };
                  default:
                        return { width: 160, height: 160 };
            }
      }
}

